use std::fs;
use std::path::Path;

use anyhow::Result;

use crate::config::Provider;
use crate::migrate::profile::{Keys, ModelProfile};

pub fn config_lines(profile: &ModelProfile, header: &str) -> Vec<String> {
    let provider = profile.provider_or_default();
    let provider_name = match provider {
        Provider::Glm => "glm",
        Provider::Kimi => "kimi",
        Provider::Minimax => "minimax",
    };
    let mut lines = vec![header.into(), format!("provider = \"{provider_name}\"")];
    if let Some(m) = &profile.model {
        lines.push(format!("model = \"{m}\""));
    }
    if let Some(url) = &profile.base_url {
        lines.push(format!("base_url = \"{url}\""));
    }
    append_keys(&mut lines, &profile.keys);
    lines
}

pub fn write_config(profile: &ModelProfile, dir: &Path) -> Result<()> {
    fs::write(
        dir.join("config.toml"),
        config_lines(profile, "# Generated by lightrs migrate").join("\n"),
    )?;
    Ok(())
}

pub fn append_keys(lines: &mut Vec<String>, keys: &Keys) {
    if keys.glm.is_none() && keys.kimi.is_none() && keys.minimax.is_none() {
        return;
    }
    lines.push("[keys]".into());
    if let Some(k) = &keys.glm {
        lines.push(format!("glm = \"{k}\""));
    }
    if let Some(k) = &keys.kimi {
        lines.push(format!("kimi = \"{k}\""));
    }
    if let Some(k) = &keys.minimax {
        lines.push(format!("minimax = \"{k}\""));
    }
}