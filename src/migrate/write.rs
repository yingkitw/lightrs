use std::fs;
use std::path::Path;

use anyhow::Result;

use crate::config::Provider;
use crate::migrate::profile::{Keys, ModelProfile};

pub fn config_lines(profile: &ModelProfile, header: &str) -> Vec<String> {
    let provider = profile.provider_or_default();
    let provider_name = match provider {
        Provider::Glm => "glm",
        Provider::Kimi => "kimi",
        Provider::Minimax => "minimax",
    };
    let mut lines = vec![header.into(), format!("provider = \"{provider_name}\"")];
    if let Some(m) = &profile.model {
        lines.push(format!("model = \"{m}\""));
    }
    if let Some(url) = &profile.base_url {
        lines.push(format!("base_url = \"{url}\""));
    }
    append_keys(&mut lines, &profile.keys);
    append_endpoints(&mut lines, profile);
    lines
}

/// `[endpoints]` for non-active providers — the chosen provider's URL is
/// already the top-level `base_url`, so duplicating it would be dead data.
pub fn append_endpoints(lines: &mut Vec<String>, profile: &ModelProfile) {
    let extra: Vec<_> = profile
        .endpoints
        .iter()
        .filter(|(p, _)| Some(**p) != profile.provider)
        .collect();
    if extra.is_empty() {
        return;
    }
    lines.push("[endpoints]".into());
    for (p, url) in extra {
        lines.push(format!("{} = \"{url}\"", p.id()));
    }
}

pub fn write_config(profile: &ModelProfile, dir: &Path) -> Result<()> {
    fs::write(
        dir.join("config.toml"),
        config_lines(profile, "# Generated by lightrs migrate").join("\n") + "\n",
    )?;
    Ok(())
}

pub fn append_keys(lines: &mut Vec<String>, keys: &Keys) {
    if keys.glm.is_none() && keys.kimi.is_none() && keys.minimax.is_none() {
        return;
    }
    lines.push("[keys]".into());
    if let Some(k) = &keys.glm {
        lines.push(format!("glm = \"{k}\""));
    }
    if let Some(k) = &keys.kimi {
        lines.push(format!("kimi = \"{k}\""));
    }
    if let Some(k) = &keys.minimax {
        lines.push(format!("minimax = \"{k}\""));
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn profile(provider: Provider) -> ModelProfile {
        ModelProfile {
            provider: Some(provider),
            model: Some("m1".into()),
            base_url: Some("https://x/v1".into()),
            keys: Keys::default(),
            ..Default::default()
        }
    }

    #[test]
    fn config_lines_maps_provider_and_optionals() {
        for (p, name) in [
            (Provider::Glm, "glm"),
            (Provider::Kimi, "kimi"),
            (Provider::Minimax, "minimax"),
        ] {
            let lines = config_lines(&profile(p), "# h");
            let text = lines.join("\n");
            assert!(text.contains(&format!("provider = \"{name}\"")), "{text}");
            assert!(text.contains("model = \"m1\""));
            assert!(text.contains("base_url = \"https://x/v1\""));
            assert!(!text.contains("[keys]"));
        }
    }

    #[test]
    fn append_endpoints_writes_overrides_and_skips_active() {
        let mut p = profile(Provider::Glm);
        p.endpoints
            .insert(Provider::Glm, "https://dup.example/v1".into());
        p.endpoints
            .insert(Provider::Kimi, "https://api.kimi.ai/coding/v1".into());
        let lines = config_lines(&p, "# h").join("\n");
        assert!(lines.contains("[endpoints]"), "{lines}");
        assert!(lines.contains("kimi = \"https://api.kimi.ai/coding/v1\""), "{lines}");
        // Active provider's endpoint is the top-level base_url — not repeated.
        assert!(!lines.contains("dup.example"), "{lines}");
    }

    #[test]
    fn config_lines_skips_absent_model_and_url() {
        let mut p = profile(Provider::Kimi);
        p.model = None;
        p.base_url = None;
        let text = config_lines(&p, "# h").join("\n");
        assert!(!text.contains("model =") && !text.contains("base_url"));
    }

    #[test]
    fn append_keys_writes_section_per_set_key() {
        let mut lines = vec!["provider = \"kimi\"".to_string()];
        let keys = Keys {
            glm: Some("g".into()),
            kimi: None,
            minimax: Some("mm".into()),
        };
        append_keys(&mut lines, &keys);
        let text = lines.join("\n");
        assert!(text.contains("[keys]"));
        assert!(text.contains("glm = \"g\""));
        assert!(text.contains("minimax = \"mm\""));
        assert!(!text.contains("kimi ="));

        let mut none = Vec::new();
        append_keys(&mut none, &Keys::default());
        assert!(none.is_empty());
    }

    #[test]
    fn write_config_lands_in_dir() {
        let dir = std::env::temp_dir().join(format!("lb-mig-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        write_config(&profile(Provider::Kimi), &dir).unwrap();
        let text = fs::read_to_string(dir.join("config.toml")).unwrap();
        assert!(text.starts_with("# Generated by lightrs migrate"));
        // Trailing newline: POSIX text-file convention and keeps later
        // appends (`key = value` merges) from gluing onto the last line.
        assert!(text.ends_with('\n'));
        let _ = fs::remove_dir_all(&dir);
    }
}